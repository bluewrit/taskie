def make_docx() -> bytes:
    import docx

    doc = docx.Document()
    doc.add_heading("Q3 Product Review", level=1)
    doc.add_paragraph("Prepared by the product team. This document summarises progress "
                      "against the Q3 roadmap and lists risks for the coming sprint.")
    doc.add_heading("Key metrics", level=2)
    table = doc.add_table(rows=4, cols=2)
    data = [("Metric", "Value"), ("Activation rate", "62%"),
            ("Weekly active users", "18,400"), ("Churn", "2.1%")]
    for i, (a, b) in enumerate(data):
        table.rows[i].cells[0].text = a
        table.rows[i].cells[1].text = b
    doc.add_paragraph("Next steps: ship the onboarding revamp and re-measure in two weeks.")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


