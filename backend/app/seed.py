def make_pdf() -> bytes:
    """Build a minimal, valid, browser-renderable PDF with a little text."""
    lines = [
        "BT /F1 22 Tf 72 720 Td (Taskie Sample Report) Tj ET",
        "BT /F1 12 Tf 72 680 Td (This PDF was generated by the seed script.) Tj ET",
        "BT /F1 12 Tf 72 660 Td (Browsers render it inline via the preview pane.) Tj ET",
    ]
    stream = "\n".join(lines).encode()
    objects = [
        b"<</Type/Catalog/Pages 2 0 R>>",
        b"<</Type/Pages/Kids[3 0 R]/Count 1>>",
        b"<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 792]/Contents 4 0 R"
        b"/Resources<</Font<</F1 5 0 R>>>>>>",
        b"<</Length " + str(len(stream)).encode() + b">>stream\n" + stream + b"\nendstream",
        b"<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for i, obj in enumerate(objects, 1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n".encode() + obj + b"\nendobj\n")
    xref_pos = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n".encode())
    out.write(b"0000000000 65535 f \n")
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(f"trailer\n<</Size {len(objects) + 1}/Root 1 0 R>>\nstartxref\n{xref_pos}\n%%EOF".encode())
    return out.getvalue()


def make_png() -> bytes:
    """64x64 gradient PNG, pure stdlib."""
    w = h = 64
    raw = b""
    for y in range(h):
        raw += b"\x00"  # filter: none
        for x in range(w):
            raw += bytes([99 + x * 2, 102, 241 - y * 2, 255])

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(raw))
            + chunk(b"IEND", b""))


def make_wav() -> bytes:
    """1 second 440Hz tone."""
    buf = io.BytesIO()
    with wave.open(buf, "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(8000)
        import math
        frames = b"".join(
            struct.pack("<h", int(12000 * math.sin(2 * math.pi * 440 * i / 8000)))
            for i in range(8000)
        )
        wf.writeframes(frames)
    return buf.getvalue()


def make_zip() -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("release-notes.txt", "v1.0.0 — initial public release of Taskie.\n")
        zf.writestr("assets/logo.svg", '<svg xmlns="http://www.w3.org/2000/svg"/>')
        zf.writestr("data/metrics.json", json.dumps({"stars": 128, "installs": 4300}))
    return buf.getvalue()


